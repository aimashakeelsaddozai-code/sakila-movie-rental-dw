--
-- Run with psql or pgAdmin Query Tool:
--   psql -U postgres -h localhost -d sakila_dw -f 04_Data_Warehouse/warehouse.sql
--
-- Safe to re-run: Drops existing tables with CASCADE in reverse dependency order.
-- ============================================================================

\set ON_ERROR_STOP on
SET client_encoding = 'UTF8';

CREATE SCHEMA IF NOT EXISTS project_dw;
SET search_path = project_dw, public;

BEGIN;

-- ----------------------------------------------------------------------------
-- 1. Drop existing tables if present (Facts first, then Dimensions)
-- ----------------------------------------------------------------------------
DROP TABLE IF EXISTS fact_film_cast CASCADE;
DROP TABLE IF EXISTS fact_inventory_daily CASCADE;
DROP TABLE IF EXISTS fact_payment CASCADE;
DROP TABLE IF EXISTS fact_rental CASCADE;

DROP TABLE IF EXISTS dim_actor CASCADE;
DROP TABLE IF EXISTS dim_staff CASCADE;
DROP TABLE IF EXISTS dim_store CASCADE;
DROP TABLE IF EXISTS dim_film CASCADE;
DROP TABLE IF EXISTS dim_customer CASCADE;
DROP TABLE IF EXISTS dim_date CASCADE;

-- ----------------------------------------------------------------------------
-- 2. Dimension Tables (Conformed & Shared Dimensions)
-- ----------------------------------------------------------------------------

-- DATE DIMENSION (Role-playing calendar dimension)
CREATE TABLE dim_date (
    date_key      INT PRIMARY KEY,                 -- YYYYMMDD format (-1 for Unknown / Not returned)
    full_date     DATE NOT NULL,                   -- Calendar date
    day_of_month  INT NOT NULL,                    -- Day number (1-31)
    day_name      VARCHAR(10) NOT NULL,            -- Monday, Tuesday, ...
    day_of_week   INT NOT NULL,                    -- 1 = Monday, 7 = Sunday (ISO 8601)
    is_weekend    CHAR(1) NOT NULL CHECK (is_weekend IN ('Y', 'N')),
    week_of_year  INT NOT NULL,                    -- ISO week number (1-53)
    month_number  INT NOT NULL,                    -- Month number (1-12)
    month_name    VARCHAR(10) NOT NULL,            -- January, February, ...
    year_month    CHAR(7) NOT NULL,                -- YYYY-MM
    quarter       INT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    year          INT NOT NULL                     -- 4-digit calendar year
);

COMMENT ON TABLE dim_date IS 'Calendar dimension generated from rental/payment date spans, with role-playing usage in rentals and payments.';
COMMENT ON COLUMN dim_date.date_key IS 'Surrogate key in YYYYMMDD format. Key -1 represents Not Returned / Unknown.';

-- CUSTOMER DIMENSION (SCD Type 2)
CREATE TABLE dim_customer (
    customer_key     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Surrogate key (-1 for Unknown)
    customer_id      INT NOT NULL,                                     -- Natural key from Sakila source
    first_name       VARCHAR(45) NOT NULL,
    last_name        VARCHAR(45) NOT NULL,
    full_name        VARCHAR(91) NOT NULL,
    email            VARCHAR(50) NOT NULL,
    address          VARCHAR(50) NOT NULL,
    district         VARCHAR(20) NOT NULL,
    city             VARCHAR(50) NOT NULL,
    country          VARCHAR(50) NOT NULL,
    postal_code      VARCHAR(10) NOT NULL,
    home_store_name  VARCHAR(50) NOT NULL,
    is_active        CHAR(1) NOT NULL CHECK (is_active IN ('Y', 'N')),
    effective_from   DATE NOT NULL,                                    -- SCD2 version validity start
    effective_to     DATE NOT NULL,                                    -- SCD2 version validity end (9999-12-31 for current)
    is_current       CHAR(1) NOT NULL CHECK (is_current IN ('Y', 'N')) -- SCD2 current flag
);

COMMENT ON TABLE dim_customer IS 'Customer dimension tracking customer profile, address, and home store changes using SCD Type 2.';

-- FILM DIMENSION (Flattened Product Dimension)
CREATE TABLE dim_film (
    film_key             INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Surrogate key (-1 for Unknown)
    film_id              INT NOT NULL,                                     -- Natural key from Sakila source
    title                VARCHAR(255) NOT NULL,
    category_name        VARCHAR(25) NOT NULL,                             -- Flattened category (Star schema)
    rating               VARCHAR(5),                                       -- G, PG, PG-13, R, NC-17
    language             VARCHAR(20) NOT NULL,                             -- Flattened language
    release_year         INT,
    length_minutes       INT,
    length_band          VARCHAR(20) NOT NULL,                             -- Short, Medium, Long
    rental_rate          DECIMAL(4,2) NOT NULL,
    rental_rate_band     VARCHAR(10) NOT NULL,                             -- Budget, Standard, Premium
    allowed_rental_days  INT NOT NULL,                                     -- Standard rental duration in days
    replacement_cost     DECIMAL(5,2) NOT NULL,
    special_features     VARCHAR(100)
);

COMMENT ON TABLE dim_film IS 'Film dimension with denormalized category and language attributes for rapid OLAP querying.';

-- STORE DIMENSION (Retail Locations)
CREATE TABLE dim_store (
    store_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Surrogate key (-1 for Unknown)
    store_id       INT NOT NULL,                                     -- Natural key from Sakila source
    store_address  VARCHAR(50) NOT NULL,
    city           VARCHAR(50) NOT NULL,
    country        VARCHAR(50) NOT NULL,
    manager_name   VARCHAR(91) NOT NULL
);

COMMENT ON TABLE dim_store IS 'Store physical location and store manager details.';

-- STAFF DIMENSION (Employees)
CREATE TABLE dim_staff (
    staff_key        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Surrogate key (-1 for Unknown)
    staff_id         INT NOT NULL,                                     -- Natural key from Sakila source
    full_name        VARCHAR(91) NOT NULL,
    email            VARCHAR(50) NOT NULL,
    home_store_name  VARCHAR(50) NOT NULL,
    is_active        CHAR(1) NOT NULL CHECK (is_active IN ('Y', 'N'))
);

COMMENT ON TABLE dim_staff IS 'Staff member dimension excluding operational credentials (password and binary picture omitted).';

-- ACTOR DIMENSION (Cast members)
CREATE TABLE dim_actor (
    actor_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, -- Surrogate key (-1 for Unknown)
    actor_id    INT NOT NULL,                                     -- Natural key from Sakila source
    first_name  VARCHAR(45) NOT NULL,
    last_name   VARCHAR(45) NOT NULL,
    full_name   VARCHAR(91) NOT NULL
);

COMMENT ON TABLE dim_actor IS 'Actor dimension containing film cast details.';

-- ----------------------------------------------------------------------------
-- 3. Fact Tables (Measures and Foreign Keys)
-- ----------------------------------------------------------------------------

-- FACT RENTAL (Transaction Fact: one row per rental event)
CREATE TABLE fact_rental (
    rental_id        INT PRIMARY KEY,                                  -- Degenerate dimension (source rental_id)
    rental_date_key  INT NOT NULL REFERENCES dim_date(date_key),
    return_date_key  INT NOT NULL REFERENCES dim_date(date_key),       -- -1 if not returned yet
    customer_key     INT NOT NULL REFERENCES dim_customer(customer_key),
    film_key         INT NOT NULL REFERENCES dim_film(film_key),
    store_key        INT NOT NULL REFERENCES dim_store(store_key),
    staff_key        INT NOT NULL REFERENCES dim_staff(staff_key),
    rental_count     INT NOT NULL DEFAULT 1,                           -- Additive unit measure (always 1)
    days_rented      INT,                                              -- return_date - rental_date (NULL if out)
    allowed_days     INT NOT NULL,                                     -- Non-additive baseline allowed duration
    days_late        INT,                                              -- GREATEST(0, days_rented - allowed_days)
    is_returned      INT NOT NULL CHECK (is_returned IN (0, 1)),
    is_late          INT NOT NULL CHECK (is_late IN (0, 1))
);

COMMENT ON TABLE fact_rental IS 'Transaction fact recording every rental, duration, timeliness, and return status.';

-- FACT PAYMENT (Transaction Fact: one row per customer payment)
CREATE TABLE fact_payment (
    payment_id        INT PRIMARY KEY,                                  -- Degenerate dimension (source payment_id)
    rental_id         INT NOT NULL,                                     -- Degenerate dimension (-1 if payment without rental)
    payment_date_key  INT NOT NULL REFERENCES dim_date(date_key),
    customer_key      INT NOT NULL REFERENCES dim_customer(customer_key),
    film_key          INT NOT NULL REFERENCES dim_film(film_key),       -- -1 if rental/film unknown
    store_key         INT NOT NULL REFERENCES dim_store(store_key),
    staff_key         INT NOT NULL REFERENCES dim_staff(staff_key),
    amount            DECIMAL(5,2) NOT NULL                             -- Additive revenue measure
);

COMMENT ON TABLE fact_payment IS 'Transaction fact tracking customer cash transactions, linking directly to revenue metrics.';

-- FACT INVENTORY DAILY (Periodic Snapshot Fact: daily film stock position by store)
CREATE TABLE fact_inventory_daily (
    snapshot_date_key  INT NOT NULL REFERENCES dim_date(date_key),
    film_key           INT NOT NULL REFERENCES dim_film(film_key),
    store_key          INT NOT NULL REFERENCES dim_store(store_key),
    copies_owned       INT NOT NULL,                                   -- Semi-additive inventory count
    copies_rented_out  INT NOT NULL,                                   -- Copies with customers at day end
    copies_available   INT NOT NULL,                                   -- Copies in stock on the shelf
    utilization_pct    DECIMAL(5,2) NOT NULL,                          -- Non-additive utilization percentage
    PRIMARY KEY (snapshot_date_key, film_key, store_key)
);

COMMENT ON TABLE fact_inventory_daily IS 'Periodic snapshot fact tracking daily store inventory availability and utilization.';

-- FACT FILM CAST (Factless Fact Table: bridge connecting films and actors)
CREATE TABLE fact_film_cast (
    film_key   INT NOT NULL REFERENCES dim_film(film_key),
    actor_key  INT NOT NULL REFERENCES dim_actor(actor_key),
    PRIMARY KEY (film_key, actor_key)
);

COMMENT ON TABLE fact_film_cast IS 'Factless fact table recording M:N actor appearances in films for cast analytics.';

-- ----------------------------------------------------------------------------
-- 4. Foreign Key Performance Indexes (Optimized for Star Joins)
-- ----------------------------------------------------------------------------

-- Indexes on fact_rental
CREATE INDEX idx_fact_rental_rental_date   ON fact_rental(rental_date_key);
CREATE INDEX idx_fact_rental_return_date   ON fact_rental(return_date_key);
CREATE INDEX idx_fact_rental_customer      ON fact_rental(customer_key);
CREATE INDEX idx_fact_rental_film          ON fact_rental(film_key);
CREATE INDEX idx_fact_rental_store         ON fact_rental(store_key);
CREATE INDEX idx_fact_rental_staff         ON fact_rental(staff_key);

-- Indexes on fact_payment
CREATE INDEX idx_fact_payment_date         ON fact_payment(payment_date_key);
CREATE INDEX idx_fact_payment_customer     ON fact_payment(customer_key);
CREATE INDEX idx_fact_payment_film         ON fact_payment(film_key);
CREATE INDEX idx_fact_payment_store        ON fact_payment(store_key);
CREATE INDEX idx_fact_payment_staff        ON fact_payment(staff_key);

-- Indexes on fact_inventory_daily
CREATE INDEX idx_fact_inv_snapshot_date    ON fact_inventory_daily(snapshot_date_key);
CREATE INDEX idx_fact_inv_film             ON fact_inventory_daily(film_key);
CREATE INDEX idx_fact_inv_store            ON fact_inventory_daily(store_key);

-- Indexes on fact_film_cast
CREATE INDEX idx_fact_cast_film            ON fact_film_cast(film_key);
CREATE INDEX idx_fact_cast_actor           ON fact_film_cast(actor_key);

-- Natural Key lookup indexes on dimensions for ETL efficiency
CREATE INDEX idx_dim_customer_nk           ON dim_customer(customer_id, is_current);
CREATE INDEX idx_dim_film_nk               ON dim_film(film_id);
CREATE INDEX idx_dim_store_nk              ON dim_store(store_id);
CREATE INDEX idx_dim_staff_nk              ON dim_staff(staff_id);
CREATE INDEX idx_dim_actor_nk              ON dim_actor(actor_id);

COMMIT;

-- Verification of created tables
SELECT table_schema, table_name, table_type
FROM information_schema.tables
WHERE table_schema = 'project_dw'
ORDER BY table_name;
